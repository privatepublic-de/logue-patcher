// Writes THIRD_PARTY_NOTICES.md: Korg's logue SDK notice (code embedded in logue-codegen) plus
// the licence text of every production npm dependency, read from node_modules. The renderer
// bundle can drop the packages' own licence comments, so the full texts live here instead.
// Re-run after changing dependencies: node scripts/write-third-party-notices.mjs
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

