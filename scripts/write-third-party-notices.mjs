const dirs = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { encoding: 'utf8' })
  .trim()
  .split('\n')
  .slice(1)

const packages = new Map()
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const id = `${pkg.name}@${pkg.version}`
  if (packages.has(id)) continue
  const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  packages.set(id, {
    id,
    license: pkg.license ?? '(see text)',
    text: licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').trim() : null
  })
}

const sorted = [...packages.values()].sort((a, b) => a.id.localeCompare(b.id))
const missing = sorted.filter((p) => !p.text).map((p) => p.id)
if (missing.length) console.warn(`no licence file found for: ${missing.join(', ')}`)

const out = [
  '# Third-party notices',
  '',
  'Logue Patcher itself is MIT-licensed (see `LICENSE`). It contains or bundles the following',
  'third-party software, each under its own licence.',
  '',
  '## Korg logue SDK',
  '',
  'Parts of the minilogue xd unit templates (`tpl/_unit.c`, linker scripts, Makefile), embedded in',
  '`logue-codegen/src/minilogue-xd/` and written into exported minilogue xd projects, and a few',
  'definitions copied into the host test harnesses under `logue-codegen/harness/`, come from',
  "Korg's logue SDK (https://github.com/korginc/logue-sdk).",
  '',
  '```',
  KORG_BSD,
  '```',
  '',
  '## npm packages bundled with the app',
  '',
  'Generated by `scripts/write-third-party-notices.mjs` from the production dependencies.',
  '',
  ...sorted.flatMap((p) => [
    `### ${p.id} (${p.license})`,
    '',
    ...(p.text
      ? ['```', p.text, '```']
      : ['No licence file in the package; licence: ' + p.license]),
    ''
  ])
].join('\n')

writeFileSync('THIRD_PARTY_NOTICES.md', out)
console.log(`wrote THIRD_PARTY_NOTICES.md (${sorted.length} packages)`)
