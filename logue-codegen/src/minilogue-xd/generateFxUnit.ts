export function generateOldGenFxUnit(
  doc: PatchDocument,
  meta: LogueOldGenOscUnitMeta,
  subpatches: SubpatchDefinitions = new Map()
): LogueOldGenFxUnitSource {
  validateNoBreakingChars(meta.name, 'Unit name')
  const module = doc.settings.logueTarget?.module ?? 'osc'
  if (!isEffectModule(module)) {
    throw new UnsupportedLogueNodeError(
      'This is an oscillator patch -- it builds with generateOldGenOscUnit, not as an effect.'
    )
  }
  const kind = findUnitKind('minilogue-xd', module)!
  const { activeInstances, exposedParams, knobBindings, stereoSinks, audioInSuffix } = resolveUnit(
    doc,
    subpatches,
    'minilogue-xd',
    { maxParamCount: kind.maxParams }
  )
  const sdram = sdramLayout(activeInstances)
  const sdramBytes = sdram.totalFloats * 4
  if (sdramBytes > (kind.sdramBytes ?? 0)) {
    throw new UnsupportedLogueNodeError(
      `The delay lines need ${formatKb(sdramBytes)} of SDRAM, more than a minilogue xd ${MODULE_LABEL[kind.module].toLowerCase()} unit's ${formatKb(kind.sdramBytes ?? 0)} -- shorten a RANGE or use fewer.`
    )
  }
  const pieces = buildOscBodyPieces(activeInstances, exposedParams, 'out', undefined, knobBindings)
  return {
    module,
    manifestJson: generateManifestJson(module, meta),
    projectMk: PROJECT_MK,
    fxCpp: generateFxCpp(kind, pieces, stereoSinks!, audioInSuffix, sdram),
    makefile: generateMakefile(module),
    unitC: generateUnitC(module),
    rulesLd: FX_RULES_LD,
    moduleLd: generateModuleLd(kind),
    mainApiSyms: MAIN_API_SYMS
  }
}
